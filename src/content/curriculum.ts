import type { CurriculumDay, Phase } from './types'

/** Day titles follow /CURRICULUM.md (the 100-day roadmap). lessonId marks the days that are interactive in v1. */
function days(first: number, titles: (string | [string, string])[]): CurriculumDay[] {
  return titles.map((t, i) => (typeof t === 'string' ? { day: first + i, title: t } : { day: first + i, title: t[0], lessonId: t[1] }))
}

